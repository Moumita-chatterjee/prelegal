// Embeds the raw legal document templates (templates/*.md at the repo root)
// into a generated TS module so the (statically-exported) frontend never has
// to hand-transcribe boilerplate legal text, and can never drift from the
// source templates. Runs before dev/build (see package.json "predev"/"prebuild").
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
// frontend/scripts -> repo root/templates (also true inside the Docker
// frontend-builder stage, which copies templates/ to /templates, a sibling
// of /frontend).
const templatesDir = join(__dirname, "..", "..", "templates");

const filenames = [
  "Mutual-NDA.md",
  "Pilot-Agreement.md",
  "CSA.md",
  "sla.md",
  "psa.md",
  "Software-License-Agreement.md",
  "Partnership-Agreement.md",
  "DPA.md",
  "BAA.md",
  "AI-Addendum.md",
  "design-partner-agreement.md",
];

const entries = filenames.map((filename) => {
  const content = readFileSync(join(templatesDir, filename), "utf-8");
  return [filename, content];
});

const body = entries
  .map(([filename, content]) => `  ${JSON.stringify(filename)}: ${JSON.stringify(content)},`)
  .join("\n");

const outDir = join(__dirname, "..", "lib", "documents");
mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, "generated.ts"),
  `// AUTO-GENERATED by scripts/generate-templates.mjs — do not edit by hand.\n` +
    `export const RAW_TEMPLATES: Record<string, string> = {\n${body}\n};\n`,
);

console.log(`generate-templates: embedded ${entries.length} template files`);
